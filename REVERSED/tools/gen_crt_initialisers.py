"""gen_crt_initialisers.py - the game's static initialisers, for a rebuild that skips the 2001 CRT startup.

Why this exists
---------------
`harness/exe_main.c` replaces the original entry point with the modern CRT's
`WinMainCRTStartup` and calls the game's `WinMain` (`sub_41D350`).  That skips one thing the
2001 startup did: running the compiler's initialiser tables.  The original entry (0x563EE0)
calls `_cinit` (0x563B87) just before `WinMain`, and `_cinit` runs both tables through
`_initterm` (0x563C6F, a loop that calls every non-null pointer in a range):

    _initterm(0x570000, 0x570260)     152 slots, 151 non-null
    _initterm(0x570264, 0x570278)       5 slots,   4 non-null

An entry is either the initialiser itself or a 5-byte `jmp` stub onto it, which is why every
entry is resolved through its `jmp` chain here: 71 are plain functions and 84 are stubs
(0x402750 -> 0x402760).  Their bodies look like this - a guard bit plus a registration with
the CRT's atexit machinery:

    void sub_402710(void) {
        if ((DAT_006da5a8 & 1) == 0) DAT_006da5a8 = DAT_006da5a8 | 1;
        sub_5626AD(&DAT_00402740);
    }

Without them a global object keeps its load-time value: `DAT_00583410`, the head of the
DirectDraw object list, is declared `dd ?` - zero - and the teardown `sub_40FD00`
dereferences it (measured: the access violation after `[main] E`).

The table addresses are recorded rather than rediscovered by a disassembler run: they come
from `_cinit`'s two `_initterm` calls, which is the evidence.

Writes
------
  src_generated/crt_initialisers.txt   every address to create in the analysis: the entries
                                       plus their resolved targets, for
                                       tools/ExportDecompiledC.java
  harness/crt_initialisers.c           the call table - resolved targets, in table order,
                                       limited to the ones that have a body *now*, so this
                                       can be run before or after the export
"""
from __future__ import annotations

import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from pe_tools import PE  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
EXE = ROOT.parent / "WAD" / "groove.exe"

# (begin, end) of each _initterm range, as `_cinit` at 0x563B87 passes them.
TABLES = [
    ("C initialisers", 0x570000, 0x570260),
    ("C++ constructors", 0x570264, 0x570278),
]
TEXT_LO, TEXT_HI = 0x401000, 0x56E000


def resolve(pe: PE, va: int, depth: int = 0) -> int:
    """Follow a 5-byte `jmp rel32` chain to the initialiser it stands for."""
    if depth > 4:
        return va
    raw = pe.read(va, 5)
    if len(raw) == 5 and raw[0] == 0xE9:
        target = (va + 5 + struct.unpack_from("<i", raw, 1)[0]) & 0xFFFFFFFF
        if TEXT_LO <= target < TEXT_HI:
            return resolve(pe, target, depth + 1)
    return va


def main() -> int:
    pe = PE(EXE)
    entries: list[tuple[str, int]] = []
    for label, begin, end in TABLES:
        raw = pe.read(begin, end - begin)
        for i in range((end - begin) // 4):
            ptr = struct.unpack_from("<I", raw, i * 4)[0]
            if ptr == 0:
                continue                        # _initterm skips nulls
            if not (TEXT_LO <= ptr < TEXT_HI):
                raise SystemExit("%s slot %d: 0x%X is not in .text" % (label, i, ptr))
            entries.append((label, ptr))

    # the analysis has to create the entries *and* the bodies their stubs jump to
    wanted: list[int] = []
    for _, a in entries:
        for va in (a, resolve(pe, a)):
            if va not in wanted:
                wanted.append(va)
    (ROOT / "src_generated" / "crt_initialisers.txt").write_text(
        "\n".join("0x%06X" % a for a in wanted) + "\n", encoding="utf-8")

    calls = [resolve(pe, a) for _, a in entries]
    have = [a for a in calls if (ROOT / "decompiled" / ("sub_%06X.c" % a)).exists()]
    missing = [a for a in calls if a not in have]

    lines = [
        "/* crt_initialisers.c - generated by tools/gen_crt_initialisers.py; do not edit.",
        " *",
        " * The game's static initialisers, in the order the 2001 CRT's `_initterm` ran them",
        " * (entry -> _cinit at 0x563B87 -> `_initterm(0x570000,0x570260)` and",
        " * `_initterm(0x570264,0x570278)`).  harness/exe_main.c calls them before the game's",
        " * WinMain, because a rebuild that skips the 2001 startup otherwise never runs them.",
        " *",
        " * Each entry is resolved through its `jmp` stub, so what is called is the real body.",
        " * Only entries with a decompiled body are listed; an undefined reference would just",
        " * fail the link.  Counts:",
        " *   %d entries in the tables, %d resolved, %d with a body, %d without." %
        (len(entries), len(set(calls)), len(have), len(missing)),
        " */",
        '#include "ghidra_prototypes.h"',
        "",
    ]
    if have:
        lines.append("void (*const groove_crt_initialisers[])(void) = {")
        for a in have:
            lines.append("    (void (*)(void))sub_%06X," % a)
        lines.append("};")
        lines.append("const unsigned int groove_crt_initialiser_count = %d;" % len(have))
    else:
        lines.append("void (*const groove_crt_initialisers[1])(void) = { 0 };")
        lines.append("const unsigned int groove_crt_initialiser_count = 0;")
    lines.append("")
    (ROOT / "harness" / "crt_initialisers.c").write_text("\n".join(lines), encoding="utf-8")

    print("entries in the tables   : %d" % len(entries))
    print("addresses for the export: %d (entries + jmp targets)" % len(wanted))
    print("resolved call targets   : %d" % len(set(calls)))
    print("  with a body now       : %d" % len(have))
    print("  without a body        : %d" % len(missing))
    if missing:
        print("    first 12:", " ".join("0x%06X" % a for a in missing[:12]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
